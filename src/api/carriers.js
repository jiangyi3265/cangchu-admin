import request from '@/utils/request'
const base='/warehouse/carriers', part=value=>encodeURIComponent(String(value))
const mutation=(url,data,method='post')=>request({url:base+url,method,data,timeout:120000,headers:{repeatSubmit:false}})
export const carrierCapabilities=()=>request({url:base+'/capabilities'})
export const carrierConnections=()=>request({url:base+'/connections'})
export const carrierConnection=id=>request({url:base+'/connections/'+part(id)})
export const saveCarrierConnection=(id,data)=>mutation('/connections'+(id?'/'+part(id):''),data,id?'put':'post')
export const carrierShipments=params=>request({url:base+'/shipments',params})
export const carrierShipment=id=>request({url:base+'/shipments/'+part(id)})
export const orderCarrierShipments=id=>request({url:base+'/orders/'+part(id)})
export const carrierServices=(id,data)=>mutation('/orders/'+part(id)+'/services',data)
export const bookCarrier=(id,data)=>mutation('/orders/'+part(id)+'/book',data)
export const recoverCarrier=id=>mutation('/shipments/'+part(id)+'/recover')
export const resolveCarrierBooking=(id,requestId)=>mutation('/orders/'+part(id)+'/resolve',{requestId})
export const resolveCarrierConfig=(id,requestId)=>mutation('/connections/'+part(id)+'/resolve',{requestId})
export const carrierLabel=(id,index)=>request({url:base+'/shipments/'+part(id)+'/labels/'+part(index),responseType:'blob'})
